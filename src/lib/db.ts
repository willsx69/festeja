const providerRatingJoin = `
     LEFT JOIN (
       SELECT provider_user_id,
              COUNT(*) AS total,
              AVG(rating) AS average
       FROM reviews
       WHERE hidden = 0
       GROUP BY provider_user_id
     ) rating_stats ON rating_stats.provider_user_id = p.user_id`;


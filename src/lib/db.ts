export type ModerationAction = {
  id: string;
  action: string;
  note: string | null;
  adminName: string;
  createdAt: string;
};

export async function listReports(): Promise<
  {
    id: string;
    reason: string;
    status: ReportStatus;
    createdAt: string;
    resolvedAt: string | null;
    resolvedByName: string | null;
    resolutionNote: string | null;
    history: ModerationAction[];
    review: ProviderReview & {
      hidden: boolean;
      providerUsername: string;
      providerName: string;
    };
  }[]
> {
  const data = await rows<{
    id: string;
    reason: string;
    status: string;
    created_at: string;
    resolved_at: string | null;
    resolution_note: string | null;
    review_id: string;
    author_name: string;
    event: string;
    event_date: string;
    rating: number;
    comment: string;
    hidden: number;
    provider_username: string;
    provider_name: string;
    resolved_by_name: string | null;
  }>(
    `SELECT rp.id, rp.reason, rp.status, rp.created_at, rp.resolved_at, rp.resolution_note,
            r.id AS review_id, r.author_name, r.event, r.event_date,
            r.rating, r.comment, r.hidden, p.username AS provider_username, pu.name AS provider_name,
            admin.name AS resolved_by_name
     FROM review_reports rp
     JOIN reviews r ON r.id = rp.review_id
     JOIN provider_profiles p ON p.user_id = r.provider_user_id
     JOIN users pu ON pu.id = r.provider_user_id
     LEFT JOIN users admin ON admin.id = rp.resolved_by
     ORDER BY CASE rp.status WHEN 'aberta' THEN 0 WHEN 'em_analise' THEN 1 ELSE 2 END,
              rp.created_at DESC`,
  );

  const actionRows = await rows<{
    id: string;
    report_id: string;
    action: string;
    note: string | null;
    created_at: string;
    admin_name: string;
  }>(
    `SELECT ma.id, ma.report_id, ma.action, ma.note, ma.created_at, u.name AS admin_name
     FROM moderation_actions ma
     JOIN users u ON u.id = ma.admin_user_id
     ORDER BY ma.created_at DESC`,
  );

  const historyByReport = new Map<string, ModerationAction[]>();
  for (const action of actionRows) {
    const list = historyByReport.get(action.report_id) ?? [];
    list.push({
      id: action.id,
      action: action.action,
      note: action.note,
      adminName: action.admin_name,
      createdAt: action.created_at,
    });
    historyByReport.set(action.report_id, list);
  }

  return data.map((report) => ({
    id: report.id,
    reason: report.reason,
    status: report.status as ReportStatus,
    createdAt: report.created_at,
    resolvedAt: report.resolved_at,
    resolvedByName: report.resolved_by_name,
    resolutionNote: report.resolution_note,
    history: historyByReport.get(report.id) ?? [],
    review: {
      id: report.review_id,
      author: report.author_name,
      event: report.event,
      date: report.event_date,
      rating: report.rating,
      comment: report.comment,
      hidden: report.hidden === 1,
      providerUsername: report.provider_username,
      providerName: report.provider_name,
    },
  }));
}


export async function canReviewContract(
  contractId: string,
  clientUserId: string,
): Promise<{ ok: true; contract: Contract } | { ok: false; reason: string }> {
  const contract = await getContract(contractId);
  if (!contract) return { ok: false, reason: "Contrato não encontrado." };

  const data = await row<{ client_user_id: string; status: string }>(
    "SELECT client_user_id, status FROM contracts WHERE id = ?",
    [contractId],
  );
  if (!data) return { ok: false, reason: "Contrato não encontrado." };

  if (data.client_user_id !== clientUserId) {
    return { ok: false, reason: "Este contrato não pertence à sua conta." };
  }
  if (data.status !== "concluido") {
    return { ok: false, reason: "Só é possível avaliar contratos concluídos." };
  }

  const existing = await row("SELECT 1 FROM reviews WHERE contract_id = ?", [
    contractId,
  ]);
  if (existing) return { ok: false, reason: "Este contrato já foi avaliado." };

  return { ok: true, contract };
}


let readyPromise: Promise<void> | undefined;

async function ensureReady(): Promise<DbDriver> {
  const driver = await getDriver();
  if (!readyPromise) {
    readyPromise = initialize(driver).catch((error) => {
      readyPromise = undefined;
      throw error;
    });
  }
  await readyPromise;
  return driver;
}

async function rawRows<T>(
  driver: DbDriver,
  sql: string,
  params?: readonly unknown[],
): Promise<T[]> {
  return (await driver.query<T>(sql, params)).rows;
}

async function rawRow<T>(
  driver: DbDriver,
  sql: string,
  params?: readonly unknown[],
): Promise<T | undefined> {
  return (await rawRows<T>(driver, sql, params))[0];
}

async function rows<T>(sql: string, params?: readonly unknown[]): Promise<T[]> {
  const driver = await ensureReady();
  return rawRows<T>(driver, sql, params);
}

async function row<T>(sql: string, params?: readonly unknown[]): Promise<T | undefined> {
  return (await rows<T>(sql, params))[0];
}

async function run(sql: string, params?: readonly unknown[]): Promise<number> {
  const driver = await ensureReady();
  return (await driver.query(sql, params)).rowCount;
}

export async function queryRows<T>(
  sql: string,
  params?: readonly unknown[],
): Promise<T[]> {
  return rows<T>(sql, params);
}

export async function queryRow<T>(
  sql: string,
  params?: readonly unknown[],
): Promise<T | undefined> {
  return row<T>(sql, params);
}

export async function execute(
  sql: string,
  params?: readonly unknown[],
): Promise<number> {
  return run(sql, params);
}

export async function withTransaction<T>(
  fn: (query: DbQuery) => Promise<T>,
): Promise<T> {
  const driver = await ensureReady();
  return driver.transaction(fn);
}

function shouldSeedDatabase(): boolean {
  if (process.env.NODE_ENV === "production") return false;
  const flag = process.env.FESTEJA_SEED?.trim().toLowerCase();
  if (flag === "1" || flag === "true") return true;
  if (flag === "0" || flag === "false") return false;
  return true;
}

export function resolveDatabasePath(): string {
  const configured = process.env.FESTEJA_DB_PATH?.trim();
  if (configured) return path.resolve(configured);
  return path.join(process.cwd(), "data", "festeja.db");
}

async function initialize(driver: DbDriver) {
  await driver.exec(SCHEMA);
  await applyMigrations(driver);
  if (shouldSeedDatabase()) await seedDatabase(driver);
}

export async function closeDb(): Promise<void> {
  readyPromise = undefined;
  await resetDriver();
}

